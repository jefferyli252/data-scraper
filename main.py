    stock = read_csv('NVDA.csv', header = 0, index_col = 0, parse_dates = True, date_parser = parser)
    stock.index = stock.index.to_period('M')

    # squeeze the DataFrame to a Series and select the 'Adj Close' column
    target_var = stock['Adj Close']

    # fit model
    model = ARIMA(target_var, order = (5, 1, 1))
    model_fit = model.fit()

    # summary of fit model
    print(model_fit.summary())

    # line plot of residuals
    residuals = DataFrame(model_fit.resid)
    residuals.plot()
    plt.title('Fit Residual Error Line Plot')
    plt.show()

    # density plot of residuals
    residuals.plot(kind = 'kde')
    plt.title('Fit Residual Error Density Plot')
    plt.show()

    # summary stats of residuals
    print(residuals.describe())

    """Model"""

    #split data
    X = stock.values
    size = int(len(X) * 0.6)
    train, test = X[0:size], X[size:len(X)]
    history = train.copy()  # Make a copy of the training data
    predictions = []

    # Select the first column of history
    endog = history[:, 0]

    # Walk-forward validation
    for i in range(len(test)):
        # Fit ARIMA model
        model = ARIMA(endog, order = (5, 1, 1))
        model_fit = model.fit()

        # Make one-step ahead forecast
        output = model_fit.forecast()
        y_hat = output[0]

        # Append forecast to predictions list
        predictions.append(y_hat)

        # Update endog with observed value from test set
        obs = test[i][0]  # Extract the first value from the test set
        endog = np.append(endog, obs)

    #evaluation plot and RMSE
    # Convert predictions to a NumPy array
    predictions_np = np.array(predictions)

    #root mean squared error
    rmse = np.sqrt(np.mean((test[:, 0] - predictions_np) ** 2))  # Calculate RMSE for the first column only, ** 2 is ^2

    # Plot forecasts against actual outcomes
    plt.plot(test[:, 0], label = 'Actual')
    plt.plot(predictions_np, color = 'r', label = 'Predicted')

    # Add labels and legend
    plt.xlabel('Index')
    plt.ylabel('Value')
    plt.legend()

    plt.show()

    print('Test RMSE: %.3f' % rmse)

    #plot adj close over time
    dates = stock.index.to_timestamp() # Convert Period index to datetime objects

    #plot
    plt.plot(dates, stock['Adj Close'])
    plt.xlabel('Date')
    plt.ylabel('Adjusted Close Price')
    plt.title('Adjusted Close Price Over Time')
    plt.show()

    """Using the model"""

    # Convert PeriodIndex to Timestamp
    stock.index = stock.index.to_timestamp()

    # Generate Future Dates
    future_dates = pd.date_range(start = stock.index[-1], periods = 100, freq = 'D')

    # Make Predictions
    predicted_values = model_fit.forecast(steps = 100)  # Forecast the next 'steps periods

    # Visualize Predictions
